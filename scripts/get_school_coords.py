def get_onemap_token(email: str, password: str) -> str:
    resp = requests.post(
        "https://www.onemap.gov.sg/api/auth/post/getToken",
        json={"email": email, "password": password},
    )
    resp.raise_for_status()
    return resp.json()["access_token"]


def geocode(school: str, headers: dict) -> tuple:
    resp = requests.get(
        "https://www.onemap.gov.sg/api/common/elastic/search",
        params={"searchVal": school, "returnGeom": "Y", "getAddrDetails": "N", "pageNum": 1},
        headers=headers,
    )
    resp.raise_for_status()
    results = resp.json().get("results", [])
    if not results:
        return (None, None)
    return (float(results[0]["LATITUDE"]), float(results[0]["LONGITUDE"]))


def main():
    load_dotenv()
    token = get_onemap_token(os.getenv("ONEMAP_EMAIL"), os.getenv("ONEMAP_PASSWORD"))
    headers = {"Authorization": token}

    new_rows = []
    for name in educational_institutions:
        lat, lon = geocode(name, headers)
        if lat is None:
            print(f"Not found: {name}")
        new_rows.append({"school_name": name, "latitude": lat, "longitude": lon})

    school_df = pd.DataFrame(new_rows)

    os.makedirs("data", exist_ok=True)
    school_df.to_csv("data/school_coords.csv", index=False)
    missing = school_df["latitude"].isna().sum()
    print(f"Saved {len(school_df)} institutions to data/school_coords.csv. {missing} missing coordinates for institution(s) were found.")


if __name__ == "__main__":
    main()
